<script>
const backendUrl = @json(rtrim(env('APP_URL', 'http://127.0.0.1:8000'), '/'));
const imagePath = document.getElementById('imagePath');
const imageFile = document.getElementById('imageFile');
const imagePreview = document.getElementById('imagePreview');
const previewImage = document.getElementById('productImagePreview');
function refreshImagePreview(){
    const path = imagePath.value.trim();
    if (!path) { imagePreview.classList.remove('has-image'); previewImage.removeAttribute('src'); return; }
    const encodedPath = path.replace(/^\/+/, '').split('/').map(encodeURIComponent).join('/');
    const url = /^https?:\/\//i.test(path) ? path : (/^\/?storage\//i.test(path) ? backendUrl + '/' + encodedPath : backendUrl + '/product-assets/' + encodedPath);
    previewImage.onload = () => imagePreview.classList.add('has-image');
    previewImage.onerror = () => imagePreview.classList.remove('has-image');
    previewImage.src = url;
}
imagePath.addEventListener('input', refreshImagePreview);
imageFile.addEventListener('change', () => { const file = imageFile.files[0]; if (!file) { refreshImagePreview(); return; } previewImage.onload = () => imagePreview.classList.add('has-image'); previewImage.src = URL.createObjectURL(file); });
refreshImagePreview();

const specificationRows = document.getElementById('adminSpecificationRows');
const specificationsJson = document.getElementById('specificationsJson');
const availabilitySelect = document.querySelector('select[name="availability"]');
const quoteOnlyCheckbox = document.getElementById('isQuoteOnly');
const availabilityHelp = document.getElementById('availabilityHelp');
let specificationValues = {};
try {
    specificationValues = JSON.parse(specificationsJson?.value || '{}');
} catch (error) {
    specificationValues = {};
}

function addSpecificationRow(key = '', value = '') {
    if (!specificationRows) return;
    const row = document.createElement('tr');
    row.innerHTML = `<td><input type="text" class="specification-key" value="${escapeSpecificationValue(key)}" placeholder="e.g. Material"></td><td><input type="text" class="specification-value" value="${escapeSpecificationValue(value)}" placeholder="e.g. Stainless steel"></td><td><button type="button" class="admin-spec-remove" aria-label="Remove specification">&times;</button></td>`;
    row.querySelector('.admin-spec-remove').addEventListener('click', () => { row.remove(); syncSpecifications(); });
    row.querySelectorAll('input').forEach(input => input.addEventListener('input', syncSpecifications));
    specificationRows.appendChild(row);
}

function escapeSpecificationValue(value) {
    return String(value ?? '').replace(/[&<>"']/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' }[character]));
}

function syncSpecifications() {
    const result = {};
    specificationRows?.querySelectorAll('tr').forEach(row => {
        const key = row.querySelector('.specification-key')?.value.trim();
        const value = row.querySelector('.specification-value')?.value.trim();
        if (key) result[key] = value;
    });
    if (specificationsJson) specificationsJson.value = JSON.stringify(result);
}

Object.entries(specificationValues || {}).forEach(([key, value]) => addSpecificationRow(key, value));
if (!Object.keys(specificationValues || {}).length) addSpecificationRow();
document.getElementById('addSpecificationRow')?.addEventListener('click', () => addSpecificationRow());
document.querySelector('form')?.addEventListener('submit', syncSpecifications);

function syncQuoteOnlyAvailability() {
    const isRequestOnly = availabilitySelect?.value === 'Available on Request';
    if (isRequestOnly && quoteOnlyCheckbox) quoteOnlyCheckbox.checked = true;
    if (quoteOnlyCheckbox) quoteOnlyCheckbox.disabled = Boolean(isRequestOnly);
    if (availabilityHelp) availabilityHelp.textContent = isRequestOnly
        ? 'This product will show Request Quote only. Customers cannot buy it or add it to their cart.'
        : 'Products marked “Available on Request” automatically use Request Quote instead of Buy or Add to Cart.';
}

availabilitySelect?.addEventListener('change', syncQuoteOnlyAvailability);
syncQuoteOnlyAvailability();

function updateStatusCardStyles() {
    const liveRadio = document.querySelector('input[name="is_active"][value="1"]');
    const cardLive = document.getElementById('statusOptionLive');
    const cardDraft = document.getElementById('statusOptionDraft');
    if (!cardLive || !cardDraft || !liveRadio) return;
    
    if (liveRadio.checked) {
        cardLive.style.borderColor = '#16845b';
        cardLive.style.background = '#f0fdf4';
        cardDraft.style.borderColor = '#d5dde7';
        cardDraft.style.background = '#ffffff';
    } else {
        cardLive.style.borderColor = '#d5dde7';
        cardLive.style.background = '#ffffff';
        cardDraft.style.borderColor = '#e06d10';
        cardDraft.style.background = '#fff7ed';
    }
}
updateStatusCardStyles();
</script>
